"""Generates docs/SOURCES.md: the source-check list from spec §5.4.

For every source URL it lists the page sections the content was written
from (hand-maintained below) and every content item that cites the URL
(generated from assets/content). Re-run after any content change:

    python3 tool/source_report.py
"""
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTENT = ROOT / "assets" / "content"
K = "https://kubernetes.io/docs/"

# Where on each page the facts come from (page section headings).
PAGE_SECTIONS = {
    K + "concepts/overview/": "intro; Why you need Kubernetes and what it can do; What Kubernetes is not; Historical context for Kubernetes",
    K + "concepts/overview/components/": "Core Components; Addons",
    K + "concepts/architecture/": "intro; Control plane components; Node components; Addons; Architecture variations",
    K + "concepts/architecture/nodes/": "Management; Self-registration of Nodes; Manual Node administration; Node status; Node heartbeats; Node controller",
    K + "concepts/architecture/control-plane-node-communication/": "Node to Control Plane; API server to kubelet; SSH tunnels; Konnectivity service",
    K + "reference/networking/ports-and-protocols/": "Control plane; Worker node(s)",
    K + "concepts/overview/working-with-objects/namespaces/": "intro; When to Use Multiple Namespaces; Initial namespaces; Working with Namespaces; Namespaces and DNS; Not all objects are in a namespace; Automatic labelling",
    K + "tasks/administer-cluster/namespaces/": "Viewing namespaces; Creating a new namespace; Deleting a namespace",
    K + "setup/learning-environment/": "Installing kubectl; Setting up local Kubernetes environments; Using online playgrounds; Practicing with production-like clusters",
    K + "tutorials/hello-minikube/": "Create a minikube cluster; Check the status of the minikube cluster; Open the Dashboard; Create a Deployment; Create a Service; Enable addons; Clean up",
    "https://minikube.sigs.k8s.io/docs/start/": "What you'll need; 3 Interact with your cluster; 4 Deploy applications; 5 Manage your cluster; closing note",
    K + "setup/production-environment/": "Production considerations; Production cluster setup (control plane, worker nodes)",
    K + "setup/production-environment/turnkey-solutions/": "intro",
    "https://docs.aws.amazon.com/eks/latest/userguide/what-is-eks.html": "Amazon EKS: Simplified Kubernetes Management; Features of Amazon EKS (Access control tools)",
    "https://cloud.google.com/kubernetes-engine/docs/concepts/kubernetes-engine-overview": "intro; Benefits of GKE (Cost optimization); How GKE works",
    "https://learn.microsoft.com/en-us/azure/aks/what-is-aks": "intro; Overview of AKS; Choose your AKS mode",
    K + "setup/production-environment/tools/kubeadm/install-kubeadm/": "Before you begin; Verify the MAC address and product_uuid; Check required ports; Swap configuration; Installing a container runtime; Installing kubeadm, kubelet and kubectl",
    K + "setup/production-environment/tools/kubeadm/create-cluster-kubeadm/": "intro; Initializing your control-plane node; Considerations about apiserver-advertise-address and ControlPlaneEndpoint; More information; Installing a Pod network add-on; Control plane node isolation; Clean up; Version skew policy; Limitations",
    K + "setup/production-environment/container-runtimes/": "intro; Install and configure prerequisites; cgroup drivers",
}


def main() -> None:
    manifest = json.loads((CONTENT / "manifest.json").read_text())
    by_url = defaultdict(list)
    for topic_id in manifest["topics"]:
        t = json.loads((CONTENT / "topics" / f"{topic_id}.json").read_text())
        for kind, key in (("section", "sections"), ("card", "flashcards"), ("question", "questions")):
            for item in t[key]:
                by_url[item["sourceUrl"]].append(f"{item['id']} ({kind})")

    missing = sorted(set(by_url) - set(PAGE_SECTIONS))
    if missing:
        raise SystemExit(f"Add page sections for: {missing}")

    lines = [
        "# Content source check",
        "",
        "Generated by `python3 tool/source_report.py` (spec §5.4). For each source",
        "page: the page sections the content was written from, then every note",
        "section, flashcard and question citing it. Reviewed against the live",
        f"pages on {manifest['reviewedAt']}.",
        "",
    ]
    for url in sorted(by_url):
        items = by_url[url]
        lines += [
            f"## {url}",
            "",
            f"**Where on the page:** {PAGE_SECTIONS[url]}",
            "",
            f"**Cited by ({len(items)}):** " + ", ".join(f"`{i}`" for i in items),
            "",
        ]
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "SOURCES.md").write_text("\n".join(lines))
    print(f"docs/SOURCES.md: {len(by_url)} pages, {sum(map(len, by_url.values()))} items")


if __name__ == "__main__":
    main()
