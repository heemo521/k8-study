"""Generates docs/SOURCES.md: the source-check list from spec §5.4.

For every subject and every cited page: the page title, the note sections
written from it, and every flashcard and question that cites it. Re-run after
any content change:

    python3 tool/source_report.py
"""
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTENT = ROOT / "assets" / "content"


def main() -> None:
    catalog = json.loads((CONTENT / "catalog.json").read_text())
    lines = [
        "# Content source check",
        "",
        "Generated by `python3 tool/source_report.py` (spec §5.4). Every note",
        "section, flashcard and question cites one page; this lists them by page so",
        "a reviewer can open each page once and check everything that cites it.",
        "",
    ]
    totals = []
    for sid in catalog["subjects"]:
        sdir = CONTENT / "subjects" / sid
        subject = json.loads((sdir / "subject.json").read_text())
        titles = {}
        sections = defaultdict(list)
        others = defaultdict(list)
        for tid in subject["topics"]:
            t = json.loads((sdir / "topics" / f"{tid}.json").read_text())
            for s in t["sections"]:
                titles.setdefault(s["sourceUrl"], s["sourceTitle"])
                sections[s["sourceUrl"]].append(f"{t['title']} › {s['heading']}")
            for kind, key in (("card", "flashcards"), ("question", "questions")):
                for item in t[key]:
                    others[item["sourceUrl"]].append(item["id"])
        urls = sorted(set(sections) | set(others))
        totals.append((sid, len(urls)))
        lines += [f"## {subject['title']} ({len(urls)} pages, reviewed {subject['reviewedAt']})", ""]
        for url in urls:
            lines.append(f"### [{titles.get(url, url)}]({url})")
            lines.append("")
            if sections[url]:
                lines.append("Notes: " + "; ".join(sections[url]))
                lines.append("")
            if others[url]:
                lines.append(f"Cited by {len(others[url])} cards/questions: "
                             + ", ".join(f"`{i}`" for i in others[url]))
                lines.append("")
    (ROOT / "docs" / "SOURCES.md").write_text("\n".join(lines))
    print("docs/SOURCES.md:", ", ".join(f"{s}: {n} pages" for s, n in totals))


if __name__ == "__main__":
    main()
